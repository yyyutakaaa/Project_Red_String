// Publishes the story cases (web/src/cases, the source of truth) for the edge functions.
//
// The interrogate function reads suspect sheets server-side from public.story_cases. This script writes:
//   supabase/seed/story_cases.sql            one upsert per case with the minified JSON
//   supabase/functions/_shared/cases/index.ts the SHA-256 of each minified case, compiled into the functions
// Apply the seed with `npx supabase db execute -f supabase/seed/story_cases.sql` (or the SQL editor), then
// GET /functions/v1/interrogate?diag=1 reports hash_ok for every case once the database matches the repo.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../src/cases');
const casesDir = path.resolve(here, '../../supabase/functions/_shared/cases');
const seedDir = path.resolve(here, '../../supabase/seed');
mkdirSync(casesDir, { recursive: true });
mkdirSync(seedDir, { recursive: true });
for (const f of readdirSync(casesDir)) if (f.endsWith('.json')) rmSync(path.join(casesDir, f));

const files = readdirSync(src).filter((f) => f.endsWith('.json')).sort();
const hashes = {};
const statements = [];
for (const f of files) {
  const id = f.replace(/\.json$/, '');
  const text = readFileSync(path.join(src, f), 'utf8').replace(/\r\n/g, '\n').trimEnd();
  if (text.includes('$case$')) throw new Error(`${f} contains the SQL quote tag $case$`);
  // The hash covers the canonical (minified) JSON, so the formatting of the stored text does not matter.
  hashes[id] = createHash('sha256').update(JSON.stringify(JSON.parse(text))).digest('hex');
  statements.push(
    `-- ${id} (sha256 of the minified JSON: ${hashes[id]})\ninsert into public.story_cases (id, case_text, updated_at) values ('${id}', $case$${text}$case$, now())\non conflict (id) do update set case_text = excluded.case_text, updated_at = now();\n`,
  );
}

writeFileSync(
  path.join(seedDir, 'story_cases.sql'),
  `-- Generated by web/scripts/sync-cases.mjs. Do not edit by hand.\n-- Story cases for the edge functions (table from migration 20261124004131_story_cases.sql).\n\n${statements.join('\n')}`,
);

const lines = [
  '// Generated by web/scripts/sync-cases.mjs. Do not edit by hand.',
  '// SHA-256 of JSON.stringify(case) for each story case. The functions load cases from public.story_cases',
  '// and only use a case whose stored text matches this hash.',
  'export const STORY_CASE_HASHES: Record<string, string> = {',
  ...Object.entries(hashes).map(([id, h]) => `  '${id}': '${h}',`),
  '};',
  '',
];
writeFileSync(path.join(casesDir, 'index.ts'), lines.join('\n'));
if (!existsSync(path.join(casesDir, 'index.ts'))) throw new Error('failed to write index.ts');
console.log(`Synced ${files.length} case(s): supabase/seed/story_cases.sql and supabase/functions/_shared/cases/index.ts`);
