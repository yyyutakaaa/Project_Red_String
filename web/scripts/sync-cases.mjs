// Copies the story case JSON files into the edge functions' shared folder so the
// interrogate function can load suspect sheets server-side. The web copy is the source of truth.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../src/cases');
const dest = path.resolve(here, '../../supabase/functions/_shared/cases');
mkdirSync(dest, { recursive: true });
for (const f of readdirSync(dest)) if (f.endsWith('.json') || f === 'index.ts') rmSync(path.join(dest, f));
const files = readdirSync(src).filter((f) => f.endsWith('.json')).sort();
for (const f of files) writeFileSync(path.join(dest, f), readFileSync(path.join(src, f), 'utf8'));
const ids = files.map((f) => f.replace(/\.json$/, ''));
const ident = (id) => id.replace(/[^a-z0-9]+(.)/g, (_, c) => c.toUpperCase());
const lines = [
  '// Generated by web/scripts/sync-cases.mjs. Do not edit by hand.',
  ...ids.map((id) => `import ${ident(id)} from './${id}.json' with { type: 'json' };`),
  '',
  'export const STORY_CASES: Record<string, unknown> = {',
  ...ids.map((id) => `  '${id}': ${ident(id)},`),
  '};',
  '',
];
writeFileSync(path.join(dest, 'index.ts'), lines.join('\n'));
console.log(`Synced ${files.length} case file(s) to ${path.relative(process.cwd(), dest)}`);
