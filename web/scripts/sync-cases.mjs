// Copies the story case JSON files into the edge functions' shared folder so the interrogate function can
// load suspect sheets server-side. The web copy (web/src/cases) is the source of truth.
// The server copies are minified, and index.ts records a SHA-256 of each one so a deployed function can
// prove (GET /functions/v1/interrogate) that it received the exact same data.
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, '../src/cases');
const dest = path.resolve(here, '../../supabase/functions/_shared/cases');
mkdirSync(dest, { recursive: true });
for (const f of readdirSync(dest)) if (f.endsWith('.json') || f === 'index.ts') rmSync(path.join(dest, f));

const files = readdirSync(src).filter((f) => f.endsWith('.json')).sort();
const hashes = {};
for (const f of files) {
  const minified = JSON.stringify(JSON.parse(readFileSync(path.join(src, f), 'utf8')));
  writeFileSync(path.join(dest, f), minified);
  hashes[f.replace(/\.json$/, '')] = createHash('sha256').update(minified).digest('hex');
}
const ids = Object.keys(hashes);
const ident = (id) => id.replace(/[^a-z0-9]+(.)/g, (_, c) => c.toUpperCase());
const lines = [
  '// Generated by web/scripts/sync-cases.mjs. Do not edit by hand.',
  ...ids.map((id) => `import ${ident(id)} from './${id}.json' with { type: 'json' };`),
  '',
  'export const STORY_CASES: Record<string, unknown> = {',
  ...ids.map((id) => `  '${id}': ${ident(id)},`),
  '};',
  '',
  '/** SHA-256 of JSON.stringify(case) for each story case, used to verify deployments. */',
  'export const STORY_CASE_HASHES: Record<string, string> = {',
  ...ids.map((id) => `  '${id}': '${hashes[id]}',`),
  '};',
  '',
];
writeFileSync(path.join(dest, 'index.ts'), lines.join('\n'));
console.log(`Synced ${files.length} case file(s) to ${path.relative(process.cwd(), dest)}`);
